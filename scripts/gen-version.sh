#!/usr/bin/env bash
set -euo pipefail

LUNAR_VERSION_BASE="0.0"

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
out="$repo_root/kernel/include/common/lunar_build_info.h"

commit="unknown"
dirty="0"

if command -v git >/dev/null 2>&1 && git -C "$repo_root" rev-parse --git-dir >/dev/null 2>&1; then
    commit="$(git -C "$repo_root" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"

    if ! git -C "$repo_root" diff-index --quiet HEAD -- 2>/dev/null; then
        dirty="1"
    fi
fi

build_date="$(date -u +'%a %b %-d %H:%M:%S UTC %Y')"

version="$LUNAR_VERSION_BASE-git-$commit"
if [ "$dirty" = "1" ]; then
    version="$version-dirty"
fi

mkdir -p -- "$(dirname -- "$out")"

cat > "$out" <<EOF
// Generated by support/gen-version.sh - do not edit.
#pragma once

#define LUNAR_BUILD_INFO_VERSION "$version"
#define LUNAR_BUILD_INFO_GIT_COMMIT "$commit"
#define LUNAR_BUILD_INFO_GIT_DIRTY $dirty
#define LUNAR_BUILD_INFO_BUILD_DATE "$build_date"
EOF

echo "gen-version: $version (built $build_date)"
